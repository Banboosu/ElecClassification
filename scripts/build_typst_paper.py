def main() -> None:
    lines = SOURCE.read_text(encoding="utf-8").splitlines()
    title = lines[0].removeprefix("# ").strip()

    zh_section = _section(lines, "## 中文摘要", "## English title")
    keyword_idx = next(i for i, line in enumerate(zh_section) if line.startswith("**关键词：**"))
    zh_abstract = _paragraph_text(zh_section[:keyword_idx])
    zh_keywords = _paragraph_text(zh_section[keyword_idx:]).replace("**关键词：**", "", 1)

    en_title_section = _section(lines, "## English title", "## Abstract")
    en_title = _strip_markdown_emphasis(_paragraph_text(en_title_section))
    en_section = _section(lines, "## Abstract", "## 1 引言")
    en_keyword_idx = next(i for i, line in enumerate(en_section) if line.startswith("**Keywords:**"))
    en_abstract = _paragraph_text(en_section[:en_keyword_idx])
    en_keywords = _paragraph_text(en_section[en_keyword_idx:]).replace("**Keywords:**", "", 1)

    body_start = lines.index("## 1 引言")
    body_end = lines.index("## 附录 A 当前结果的复现索引")
    body_text = _convert_body(lines[body_start:body_end])

    entry_text = ENTRY_TEMPLATE
    entry_text = entry_text.replace("__TITLE__", _typst_inline(title))
    entry_text = entry_text.replace("__ZH_ABSTRACT__", _typst_inline(zh_abstract))
    entry_text = entry_text.replace("__ZH_KEYWORDS__", _typst_inline(zh_keywords))
    entry_text = entry_text.replace("__EN_TITLE__", _typst_inline(en_title))
    entry_text = entry_text.replace("__EN_ABSTRACT__", _typst_inline(en_abstract))
    entry_text = entry_text.replace("__EN_KEYWORDS__", _typst_inline(en_keywords))

    ENTRY.write_text(entry_text, encoding="utf-8", newline="\n")
    BODY.write_text(body_text, encoding="utf-8", newline="\n")
    print(f"wrote {ENTRY.relative_to(ROOT)}")
    print(f"wrote {BODY.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
