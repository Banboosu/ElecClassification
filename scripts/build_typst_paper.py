"""Build the journal-formatted Typst manuscript from the Markdown draft.

The Markdown file remains the content source of truth.  This script performs a
small, deterministic conversion for the syntax used by the paper and writes a
Typst entry file plus a generated body file under ``docs/``.
"""

from __future__ import annotations

import re
from pathlib import Path


ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "docs" / "paper_draft_20260805.md"
ENTRY = ROOT / "docs" / "paper_journal_20260805.typ"
BODY = ROOT / "docs" / "paper_journal_body_20260805.typ"


def _section(lines: list[str], start: str, end: str) -> list[str]:
    start_idx = lines.index(start) + 1
    end_idx = lines.index(end, start_idx)
    return lines[start_idx:end_idx]


def _paragraph_text(lines: list[str]) -> str:
    """Join hard-wrapped prose without inserting spaces at CJK boundaries."""

    parts = [line.strip() for line in lines if line.strip()]
    if not parts:
        return ""

    result = parts[0]
    cjk_or_punctuation = re.compile(
        r"[\u3400-\u9fff，。；：、！？（）」』】》—–]"
    )
    for part in parts[1:]:
        separator = ""
        if not (
            cjk_or_punctuation.fullmatch(result[-1])
            or cjk_or_punctuation.fullmatch(part[0])
        ):
            separator = " "
        result += separator + part
    return result


def _strip_markdown_emphasis(text: str) -> str:
    return text.replace("**", "").strip()


def _typst_inline(text: str) -> str:
    """Convert the limited inline Markdown used in the manuscript."""

    replacements: list[str] = []

    def stash(value: str) -> str:
        token = f"\ue000{len(replacements)}\ue001"
        replacements.append(value)
        return token

    def code(match: re.Match[str]) -> str:
        value = match.group(1).replace("\\", "\\\\").replace('"', '\\"')
        return stash(f'#raw("{value}")')

    def link(match: re.Match[str]) -> str:
        label = match.group(1)
        url = match.group(2).replace('"', '\\"')
        return stash(f'#link("{url}")[{label}]')

    def autolink(match: re.Match[str]) -> str:
        url = match.group(1).replace('"', '\\"')
        return stash(f'#link("{url}")[{url}]')

    def bold(match: re.Match[str]) -> str:
        return stash(f'*{match.group(1)}*')

    def italic(match: re.Match[str]) -> str:
        return stash(f'_{match.group(1)}_')

    def inline_math(match: re.Match[str]) -> str:
        value = match.group(1)
        value = value.replace(r"\gamma", "gamma")
        value = value.replace(r"\in", " in ")
        value = value.replace(r"\ldots", "dots")
        value = value.replace(r"\{", "lr({").replace(r"\}", "})")
        value = re.sub(r"\^\{([^}]+)\}", r"^(\1)", value)
        return stash(f"${value}$")

    text = re.sub(r"`([^`]+)`", code, text)
    text = re.sub(r"\\\((.+?)\\\)", inline_math, text)
    text = re.sub(r"\[([^\]]+)\]\(([^)]+)\)", link, text)
    text = re.sub(r"<(https?://[^>]+)>", autolink, text)
    text = re.sub(r"\*\*([^*]+)\*\*", bold, text)
    text = re.sub(r"(?<!\*)\*([^*]+)\*(?!\*)", italic, text)
    text = text.replace("@", r"\@").replace("#", r"\#").replace("$", r"\$")

    for idx, value in enumerate(replacements):
        text = text.replace(f"\ue000{idx}\ue001", value)
    return text


def _content(value: str) -> str:
    return f"[{_typst_inline(value.strip())}]"


def _split_table_row(line: str) -> list[str]:
    return [cell.strip() for cell in line.strip().strip("|").split("|")]


def _is_separator_row(cells: list[str]) -> bool:
    return all(re.fullmatch(r":?-{3,}:?", cell) for cell in cells)


def _emit_table(caption: str, rows: list[list[str]]) -> str:
    if len(rows) < 2 or not _is_separator_row(rows[1]):
        raise ValueError(f"Malformed Markdown table below {caption!r}")

    header = rows[0]
    data = rows[2:]
    columns = len(header)
    if any(len(row) != columns for row in data):
        raise ValueError(f"Inconsistent column count below {caption!r}")

    header_cells = ", ".join(_content(cell) for cell in header)
    data_cells = ",\n    ".join(
        _content(cell) for row in data for cell in row
    )
    wide = "true" if columns >= 4 else "false"
    return (
        f"#journal-table(\n"
        f"  caption: {_content(caption)},\n"
        f"  columns: {columns},\n"
        f"  header: ({header_cells}),\n"
        f"  cells: (\n    {data_cells},\n  ),\n"
        f"  wide: {wide},\n"
        f")"
    )


def _convert_body(lines: list[str]) -> str:
    output: list[str] = [
        "// Generated by scripts/build_typst_paper.py; edit the Markdown source instead.",
        "#let paper-body(journal-table, journal-figure) = [",
    ]
    paragraph: list[str] = []
    pending_caption: str | None = None
    idx = 0

    def flush_paragraph() -> None:
        if paragraph:
            output.append(_typst_inline(_paragraph_text(paragraph)))
            output.append("")
            paragraph.clear()

    while idx < len(lines):
        line = lines[idx]
        stripped = line.strip()

        if not stripped:
            flush_paragraph()
            idx += 1
            continue

        table_caption = re.fullmatch(r"\*\*(表\s+\d+\s+.+)\*\*", stripped)
        if table_caption:
            flush_paragraph()
            pending_caption = table_caption.group(1)
            idx += 1
            continue

        if stripped.startswith("|"):
            flush_paragraph()
            rows: list[list[str]] = []
            while idx < len(lines) and lines[idx].strip().startswith("|"):
                rows.append(_split_table_row(lines[idx]))
                idx += 1
            if pending_caption is None:
                raise ValueError("Table has no preceding numbered caption")
            output.append(_emit_table(pending_caption, rows))
            output.append("")
            pending_caption = None
            continue

        figure_match = re.fullmatch(r"!\[([^]]+)\]\(([^)]+)\)", stripped)
        if figure_match:
            flush_paragraph()
            caption, path = figure_match.groups()
            wide_captions = ("典型错误", "少标签电池", "专用电池", "零样本插补")
            wide = "true" if any(value in caption for value in wide_captions) else "false"
            output.append(
                f'#journal-figure("{path}", {_content(caption)}, wide: {wide})'
            )
            output.append("")
            idx += 1
            continue

        if stripped == r"\[":
            flush_paragraph()
            while idx < len(lines) and lines[idx].strip() != r"\]":
                idx += 1
            if idx == len(lines):
                raise ValueError("Unterminated display equation")
            output.append(
                '#math.equation(block: true, $ "Macro-F1" = 1/K sum_(k=1)^K '
                '(2 P_k R_k)/(P_k + R_k), quad K = 3 $)'
            )
            output.append("")
            idx += 1
            continue

        heading_match = re.fullmatch(r"(#{2,3})\s+(.+)", stripped)
        if heading_match:
            flush_paragraph()
            level = "=" if len(heading_match.group(1)) == 2 else "=="
            output.append(f"{level} {_typst_inline(heading_match.group(2))}")
            output.append("")
            idx += 1
            continue

        ordered_match = re.match(r"^\d+\.\s+(.+)", stripped)
        bullet_match = re.match(r"^-\s+(.+)", stripped)
        if ordered_match or bullet_match:
            flush_paragraph()
            marker = "+" if ordered_match else "-"
            item = (ordered_match or bullet_match).group(1)
            idx += 1
            continuation: list[str] = []
            while idx < len(lines):
                next_line = lines[idx]
                if next_line.startswith("   ") and next_line.strip():
                    continuation.append(next_line.strip())
                    idx += 1
                else:
                    break
            value = _paragraph_text([item, *continuation])
            output.append(f"{marker} {_typst_inline(value)}")
            continue

        paragraph.append(stripped)
        idx += 1

    flush_paragraph()
    return "\n".join(output).rstrip() + "\n]\n"


